fn encode_string_list(values: Option<&[String]>) -> Result<Option<Vec<CString>>, NulError> {
    values
        .map(|values| {
            values
                .iter()
                .map(|value| CString::new(value.as_str()))
                .collect::<Result<Vec<_>, _>>()
        })
        .transpose()
}

fn string_ptrs(values: Option<&[CString]>) -> Option<Vec<*const c_char>> {
    values.map(|values| values.iter().map(|value| value.as_ptr()).collect())
}

fn option_string_ptr(value: Option<&CString>) -> *const c_char {
    value.map_or(ptr::null(), |value| value.as_ptr())
}

fn option_slice_ptr<T>(value: Option<&[T]>) -> *const T {
    value.map_or(ptr::null(), |value| {
        if value.is_empty() {
            ptr::null()
        } else {
            value.as_ptr()
        }
    })
}

fn option_slice_len<T>(value: Option<&[T]>) -> usize {
    value.map_or(0, <[T]>::len)
}

fn check_status(
    status: sys::llama_rs_status,
    error: *mut c_char,
) -> Result<(), CommonSamplerError> {
    let message = take_string(error)?.unwrap_or_else(|| "no native diagnostic".to_string());
    if status == sys::LLAMA_RS_STATUS_OK {
        Ok(())
    } else {
        Err(CommonSamplerError::Native { status, message })
    }
}

fn take_string(value: *mut c_char) -> Result<Option<String>, FromUtf8Error> {
    if value.is_null() {
        return Ok(None);
    }
    let bytes = unsafe { CStr::from_ptr(value) }.to_bytes().to_vec();
    unsafe { sys::llama_rs_string_free(value) };
    String::from_utf8(bytes).map(Some)
}

