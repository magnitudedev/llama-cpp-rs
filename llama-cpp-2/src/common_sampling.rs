//! Safe access to llama.cpp's higher-level `common/sampling` policy.
//!
//! Unlike [`crate::sampling`], this module does not require callers to reproduce
//! llama.cpp's sampler-chain construction. It preserves the pinned upstream
//! defaults and model sampling metadata, then applies only explicitly configured
//! overrides.

use std::borrow::Borrow;
use std::ffi::{c_char, CStr, CString, NulError};
use std::ptr::{self, NonNull};
use std::string::FromUtf8Error;

use llama_cpp_sys_2 as sys;

use crate::context::LlamaContext;
use crate::model::LlamaModel;
use crate::token::LlamaToken;

const NULL_TOKEN: sys::llama_token = -1;

/// A sampler-chain component, in application order.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum CommonSamplerType {
    /// Don't Repeat Yourself sequence penalty.
    Dry,
    /// Keep the highest-scoring `k` candidates.
    TopK,
    /// Nucleus sampling.
    TopP,
    /// Minimum-probability sampling.
    MinP,
    /// Locally typical sampling.
    TypicalP,
    /// Static or dynamic temperature.
    Temperature,
    /// Exclude Top Choices sampling.
    Xtc,
    /// Fill-in-the-middle sampling.
    Infill,
    /// Repeat, frequency, and presence penalties.
    Penalties,
    /// Top-n-sigma filtering.
    TopNSigma,
    /// Adaptive probability selection. When present, this selects the token in
    /// place of llama.cpp's normal distribution sampler.
    AdaptiveP,
}

impl CommonSamplerType {
    fn raw(self) -> sys::llama_rs_common_sampler_type {
        match self {
            Self::Dry => sys::LLAMA_RS_COMMON_SAMPLER_DRY,
            Self::TopK => sys::LLAMA_RS_COMMON_SAMPLER_TOP_K,
            Self::TopP => sys::LLAMA_RS_COMMON_SAMPLER_TOP_P,
            Self::MinP => sys::LLAMA_RS_COMMON_SAMPLER_MIN_P,
            Self::TypicalP => sys::LLAMA_RS_COMMON_SAMPLER_TYPICAL_P,
            Self::Temperature => sys::LLAMA_RS_COMMON_SAMPLER_TEMPERATURE,
            Self::Xtc => sys::LLAMA_RS_COMMON_SAMPLER_XTC,
            Self::Infill => sys::LLAMA_RS_COMMON_SAMPLER_INFILL,
            Self::Penalties => sys::LLAMA_RS_COMMON_SAMPLER_PENALTIES,
            Self::TopNSigma => sys::LLAMA_RS_COMMON_SAMPLER_TOP_N_SIGMA,
            Self::AdaptiveP => sys::LLAMA_RS_COMMON_SAMPLER_ADAPTIVE_P,
        }
    }
}

/// Mirostat token-selection mode.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum CommonMirostat {
    /// Use the configured sampler chain and distribution sampler.
    Disabled,
    /// Mirostat 1.0.
    Version1,
    /// Mirostat 2.0.
    Version2,
}

impl CommonMirostat {
    fn raw(self) -> i32 {
        match self {
            Self::Disabled => 0,
            Self::Version1 => 1,
            Self::Version2 => 2,
        }
    }
}

/// Why a grammar was constructed. llama.cpp uses this to decide whether an
/// assistant generation prefix must be prefilled into the grammar state.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum CommonGrammarKind {
    /// A caller-supplied GBNF grammar.
    User,
    /// A grammar generated from a response JSON Schema.
    OutputFormat,
    /// A grammar generated by the chat template for tool calls.
    ToolCalls,
}

impl CommonGrammarKind {
    fn raw(self) -> sys::llama_rs_common_grammar_type {
        match self {
            Self::User => sys::LLAMA_RS_COMMON_GRAMMAR_USER,
            Self::OutputFormat => sys::LLAMA_RS_COMMON_GRAMMAR_OUTPUT_FORMAT,
            Self::ToolCalls => sys::LLAMA_RS_COMMON_GRAMMAR_TOOL_CALLS,
        }
    }
}

/// A GBNF grammar and its semantic origin.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct CommonGrammar {
    /// Grammar origin.
    pub kind: CommonGrammarKind,
    /// GBNF source rooted at `root`.
    pub source: String,
}

/// A condition that activates a lazy grammar.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum CommonGrammarTrigger {
    /// Activate on an already-resolved token identifier.
    Token {
        /// Token identifier.
        token: LlamaToken,
        /// Optional diagnostic representation of the token.
        value: Option<String>,
    },
    /// Activate on a literal word. The native bridge resolves single-token words
    /// to token triggers exactly as llama-server does.
    Word(String),
    /// Activate when this regular expression matches.
    Pattern(String),
    /// Activate only when this regular expression matches the full text.
    PatternFull(String),
}

/// One explicit token-logit adjustment.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct CommonLogitBias {
    /// Token identifier.
    pub token: LlamaToken,
    /// Value added to the token logit. Negative infinity forbids the token.
    pub bias: f32,
}

/// Maximum reasoning generated between the configured thinking tags.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ReasoningBudgetLimit {
    /// Do not impose a numeric limit. This can still arm runtime control or
    /// suppress a lazy output grammar while the model is thinking.
    Unlimited,
    /// Force the configured ending sequence after this many generated tokens.
    Tokens(u32),
}

/// Configuration for llama.cpp's reasoning-budget sampler.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct CommonReasoningBudget {
    /// Numeric limit.
    pub limit: ReasoningBudgetLimit,
    /// Token sequence that enters the reasoning block, expressed as text and
    /// tokenized by the pinned model vocabulary.
    pub start_tag: String,
    /// Token sequence that exits the reasoning block.
    pub end_tag: String,
    /// Text inserted before `end_tag` when the limit is exhausted.
    pub forced_message: String,
    /// Keep the sampler armed for an explicit runtime `force_reasoning_end` call.
    pub controllable: bool,
}

/// Explicit overrides for `common_params_sampling`.
